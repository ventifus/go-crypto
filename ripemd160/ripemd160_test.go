func TestVectors(t *testing.T) {
	for i := 0; i < len(vectors); i++ {
		tv := vectors[i]
		md := New()
		for j := 0; j < 3; j++ {
			if j < 2 {
				io.WriteString(md, tv.in)
			} else {
				io.WriteString(md, tv.in[0:len(tv.in)/2])
				md.Sum(nil)
				io.WriteString(md, tv.in[len(tv.in)/2:])
			}
			s := fmt.Sprintf("%x", md.Sum(nil))
			if s != tv.out {
				t.Fatalf("RIPEMD-160[%d](%s) = %s, expected %s", j, tv.in, s, tv.out)
			}
			md.Reset()
		}
	}
}

func TestVectorsMarshal(t *testing.T) {
	for _, v := range vectors {
		h := New()
		h2 := New()

		io.WriteString(h, v.in[:len(v.in)/2])

		state, err := h.(encoding.BinaryMarshaler).MarshalBinary()
		if err != nil {
			t.Errorf("could not marshal: %v", err)
			continue
		}

		if string(state) != v.halfState {
			t.Errorf("ripemd160(%q) state = %q, want %q", v.in, state, v.halfState)
			continue
		}

		if err := h2.(encoding.BinaryUnmarshaler).UnmarshalBinary(state); err != nil {
			t.Errorf("could not unmarshal: %v", err)
			continue
		}

		io.WriteString(h, v.in[len(v.in)/2:])
		io.WriteString(h2, v.in[len(v.in)/2:])

		if actual, actual2 := h.Sum(nil), h2.Sum(nil); !bytes.Equal(actual, actual2) {
			t.Errorf("ripemd160(%q) = 0x%x != marshaled 0x%x", v.in, actual, actual2)
		}
	}
}

func millionA() string {
	md := New()
	for i := 0; i < 100000; i++ {
		io.WriteString(md, "aaaaaaaaaa")
	}
	return fmt.Sprintf("%x", md.Sum(nil))
}

func TestMillionA(t *testing.T) {
	const out = "52783243c1697bdbe16d37f97f68f08325dc1528"
	if s := millionA(); s != out {
		t.Fatalf("RIPEMD-160 (1 million 'a') = %s, expected %s", s, out)
	}
}

func BenchmarkMillionA(b *testing.B) {
	for i := 0; i < b.N; i++ {
		millionA()
	}
}
