func TestHashes(t *testing.T) {
	defer func(sse2, ssse3, sse4 bool) {
		useSSE2, useSSSE3, useSSE4 = sse2, ssse3, sse4
	}(useSSE2, useSSSE3, useSSE4)

	if useSSE4 {
		t.Log("SSE4 version")
		testHashes(t)
		testHashes224(t)
		testHashes160(t)
		testHashes128(t)
		useSSE4 = false
	}
	if useSSSE3 {
		t.Log("SSSE3 version")
		testHashes(t)
		testHashes224(t)
		testHashes160(t)
		testHashes128(t)
		useSSSE3 = false
	}
	if useSSE2 {
		t.Log("SSE2 version")
		testHashes(t)
		testHashes224(t)
		testHashes160(t)
		testHashes128(t)
		useSSE2 = false
	}
	if useGeneric {
		t.Log("generic version")
		testHashes(t)
		testHashes224(t)
		testHashes160(t)
		testHashes128(t)
	}
}

func testHashes(t *testing.T) {
	key, _ := hex.DecodeString("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f")

	input := make([]byte, 255)
	for i := range input {
		input[i] = byte(i)
	}

	for i, expectedHex := range hashes {
		h, err := New256(key)
		if err != nil {
			t.Fatalf("#%d: error from New256: %v", i, err)
		}

		h.Write(input[:i])
		sum := h.Sum(nil)

		if gotHex := fmt.Sprintf("%x", sum); gotHex != expectedHex {
			t.Fatalf("#%d (single write): got %s, wanted %s", i, gotHex, expectedHex)
		}

		h.Reset()
		for j := 0; j < i; j++ {
			h.Write(input[j : j+1])
		}

		sum = h.Sum(sum[:0])
		if gotHex := fmt.Sprintf("%x", sum); gotHex != expectedHex {
			t.Fatalf("#%d (byte-by-byte): got %s, wanted %s", i, gotHex, expectedHex)
		}
	}
}

